// Builds the text of src/dbSchema.generated.ts from the CURRENT database (the caller has run migrate()).
// Shared by scripts/db-types.ts (writes the file) and guards/dbTypes.guard.test.ts (compares it).
import { generate, PostgresDialect } from "kysely-codegen";
import { Kysely } from "kysely";
import { qDialect } from "../dbKysely.js";

export const GENERATED_HEADER = "// GENERATED by `npm run db:types` from the migrated schema (PGlite). Do not edit by hand.\n";

export async function generateDbTypes(): Promise<string> {
  const db = new Kysely<unknown>({ dialect: qDialect });
  const body = await generate({
    db,
    dialect: new PostgresDialect(),
    defaultSchemas: ["public"],
    excludePattern: "schema_migrations",
    skipAutogeneratedFileComment: true,
    print: false,
  });
  return GENERATED_HEADER + body;
}
