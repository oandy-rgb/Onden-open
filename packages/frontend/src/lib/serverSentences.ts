/** The sentence for a refusal the backend sent as an English sentence, or null. */
export function sentenceRefusalMessage(code: string): string | null {
  const exact = SERVER_SENTENCE_MESSAGES[code];
  if (exact) return exact;
  return SERVER_SENTENCE_PATTERNS.find(([re]) => re.test(code))?.[1] ?? null;
}
