// Generates the two highlight.js grammar tables from the installed highlight.js,
// so the list never drifts from the package and nobody copies 190 names by hand:
//   src/highlightGrammars.generated.ts, grammarTableMore.generated.ts — names, embedded grammars, aliases, the `common` subset (start-up part / the rest)
//   src/grammarLoaders.generated.ts, grammarLoadersMore.generated.ts — one lazy import() per grammar (kept apart from the table: highlight.ts must not pull the imports in)
// Run: npm run gen:grammars -w @onden/markdown. highlightGenerated.test.ts fails when the files are stale.
import hljs from "highlight.js";
import { common } from "lowlight";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const q = (s) => JSON.stringify(s);

/** The grammars a compiled language embeds through `subLanguage` (HTML colours its <script> as JavaScript). */
function embedded(def, self, all) {
  const out = new Set();
  const seen = new Set();
  const walk = (mode) => {
    if (!mode || typeof mode !== "object" || seen.has(mode)) return;
    seen.add(mode);
    if (mode.subLanguage) [mode.subLanguage].flat().forEach((s) => out.add(s));
    Object.values(mode).forEach((v) => (Array.isArray(v) ? v.forEach(walk) : walk(v)));
  };
  walk(def);
  return [...out].filter((s) => s !== self && all.has(s)).sort();
}

export function generate() {
  const names = hljs.listLanguages().sort();
  const all = new Set(names);
  const taken = new Map(names.map((n) => [n, n]));
  const rows = names.map((name) => {
    const def = hljs.getLanguage(name);
    const aliases = [];
    for (const raw of def.aliases ?? []) {
      const alias = raw.toLowerCase();
      if (taken.has(alias)) continue; // a grammar's own name wins, then the first in name order
      taken.set(alias, name);
      aliases.push(alias);
    }
    return { name, aliases, deps: embedded(def, name, all) };
  });
  const header = "// GENERATED by packages/markdown/scripts/genGrammars.mjs from highlight.js — do not edit.\n";
  // The start-up bundle carries the table for the `common` grammars and what they embed (so a note's first fence
  // resolves at once); the other ~150 names and aliases are a second table, imported when a fence names a grammar
  // outside the first (grammarTableMore). Splitting keeps ~1 KiB of names out of the code every user downloads.
  const byName = new Map(rows.map((r) => [r.name, r]));
  const boot = new Set(Object.keys(common));
  for (const n of boot) for (const d of byName.get(n).deps) boot.add(d);
  const bootRows = rows.filter((r) => boot.has(r.name));
  const moreRows = rows.filter((r) => !boot.has(r.name));
  const deps = (r) => `[${r.deps.map(q).join(", ")}]`;
  const aliases = (list) => list.filter((r) => r.aliases.length).map((r) => `  ${q(r.name)}: [${r.aliases.map(q).join(", ")}],`).join("\n");
  const table = `${header}// Start-up part of highlight.js ${hljs.versionString}'s grammar table: the \`common\` grammars, what they embed
// (\`subLanguage\`) and their aliases. The type names all of them; the rest is in grammarTableMore.generated.ts.
import type { MORE_GRAMMARS } from "./grammarTableMore.generated.js";

export const BOOT_GRAMMARS = {
${bootRows.map((r) => `  ${q(r.name)}: ${deps(r)},`).join("\n")}
} as const satisfies Record<string, readonly string[]>;

export const BOOT_ALIASES: Readonly<Record<string, readonly string[]>> = {
${aliases(bootRows)}
};

export type GrammarName = keyof typeof BOOT_GRAMMARS | keyof typeof MORE_GRAMMARS;

/** The grammars lowlight's \`common\` has: the only ones an untagged block is guessed from. */
export const COMMON_GRAMMAR_NAMES: readonly GrammarName[] = [${Object.keys(common).sort().map(q).join(", ")}];
`;
  const moreTable = `${header}// The grammars outside the start-up table (see highlightGrammars.generated.ts).

export const MORE_GRAMMARS = {
${moreRows.map((r) => `  ${q(r.name)}: ${deps(r)},`).join("\n")}
} as const satisfies Record<string, readonly string[]>;

export const MORE_ALIASES: Readonly<Record<string, readonly string[]>> = {
${aliases(moreRows)}
};
`;
  // Two files: the common grammars load from the first, every other one from a second file that is itself
  // imported on first use, so the app's start-up code carries 37 import() entries, not 192 (each one adds a
  // chunk-name entry to the start-up bundle).
  const isCommon = (n) => n in common;
  const loaderFile = (what, list, extra) => `${header}import type { LanguageFn } from "highlight.js";
${extra}
export const ${what}: Record<string, () => Promise<{ default: LanguageFn }>> = {
${list.map((n) => `  ${q(n)}: () => import(${q("highlight.js/lib/languages/" + n)}),`).join("\n")}
};
`;
  const loaders = loaderFile("COMMON_LOADERS", names.filter(isCommon), "");
  const more = loaderFile("MORE_LOADERS", names.filter((n) => !isCommon(n)), "");
  return { "highlightGrammars.generated.ts": table, "grammarTableMore.generated.ts": moreTable, "grammarLoaders.generated.ts": loaders, "grammarLoadersMore.generated.ts": more };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [file, text] of Object.entries(generate())) writeFileSync(join(here, "../src", file), text);
}
